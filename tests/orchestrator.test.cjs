const assert = require('node:assert/strict');
const O = require('../www/orchestrator.js');
const plan = O.planMission({ goal: 'بررسی جامع سایت و برنامه رشد', context: { site: 'example.test', bridgeConnected: true, report: { counts: { critical: 2, high: 3 }, pages: [] }, catalog: { items: [{ id: 1, type: 'product', title: 'قهوه' }], total: 1, complete: true } } });
assert.equal(plan.steps.length, 9);
assert.equal(plan.steps[0].id, 'seo');
assert.equal(plan.steps[plan.steps.length - 1].id, 'quality');
assert.ok(plan.steps.every((x) => x.writesAllowed === false));
(async () => {
  let checkpoints = 0;
  const done = await O.executeMission(plan, { context: { catalog: { items: [{ id: 1, type: 'product', contentPreview: '' }] }, report: { counts: { critical: 2 } } }, onCheckpoint: () => checkpoints++ });
  assert.equal(done.status, 'completed');
  assert.equal(done.report.completed, 9);
  assert.ok(checkpoints >= 10);
  assert.ok(done.report.recommendations.every((x) => x.approved === false));
  const m = O.createMemory({ type: 'brand_voice', key: 'لحن', value: 'حرفه‌ای، دقیق و بدون اغراق' });
  const merged = O.mergeMemory([], m);
  assert.equal(merged.length, 1);
  assert.throws(() => O.createMemory({ type: 'site_context', key: 'secret', value: 'api_key=abcd' }), /محرمانه/);
  const summary = O.buildContextSummary({ site: 'example.test', catalog: { total: 3, complete: true, items: [] }, integrations: { gsc: { connected: true, rows: [{ clicks: 4, impressions: 20 }, { clicks: 6, impressions: 30 }] }, ga4: { connected: true, metricHeaders: ['sessions'], rows: [{ metrics: ['17'] }] }, psi: { connected: true, url: 'https://example.test', scores: { performance: 91 } }, bing: { connected: true, traffic: [{ clicks: 2, impressions: 8 }], queries: [] } }, research: { results: [{ title: 'source', url: 'https://source.test/a', date: '2026-11-10' }] } });
  assert.equal(summary.integrations.gsc.clicks, 10);
  assert.equal(summary.integrations.ga4.metrics.sessions, 17);
  assert.equal(summary.integrations.pagespeed.scores.performance, 91);
  assert.equal(summary.integrations.bing.clicks, 2);
  assert.equal(summary.researchSources.length, 1);
  const detailed = O.buildContextSummary({ crawlReport: { job_id: 'crawl_1', status: 'completed', page_count: 12, issues: [{ severity: 'high' }], duplicate_groups: { title: [[1, 2]], meta_description: [], content_exact: [[3, 4]] } }, knowledgeStatus: { indexed: 10, total: 12, chunks: 30, mode: 'semantic', sourceMode: 'full-public-content' } });
  assert.equal(detailed.crawler.pages, 12);
  assert.equal(detailed.crawler.duplicateTitleGroups, 1);
  assert.equal(detailed.knowledge.mode, 'semantic');
  assert.equal(detailed.knowledge.indexed, 10);
  let resumed = 0; const partial = O.planMission({ goal: 'complete audit' }); partial.checkpoint = 3; partial.steps.slice(0, 3).forEach((x) => { x.status = 'completed'; });
  const resumedResult = await O.executeMission(partial, { llm: async () => { resumed++; return { findings: ['ok'], recommendations: [], confidence: 90 }; } });
  assert.equal(resumed, partial.steps.length - 3, 'resume runs only unfinished agents');
  assert.equal(resumedResult.status, 'completed');
  console.log('orchestrator tests: OK');
})().catch((e) => { console.error(e); process.exit(1); });
